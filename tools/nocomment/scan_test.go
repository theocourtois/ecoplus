package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeFile(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "x.go")
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestCheckFile(t *testing.T) {
	cases := map[string]struct {
		src  string
		want int
	}{
		"clean":       {"package x\n\nfunc F() {}\n", 0},
		"line":        {"package x\n\n// c\nfunc F() {}\n", 1},
		"block":       {"package x\n\n/* c */\nfunc F() {}\n", 1},
		"trailing":    {"package x\n\nfunc F() {} // c\n", 1},
		"directive":   {"package x\n\n//go:noinline\nfunc F() {}\n", 0},
		"generated":   {"// Code generated by x. DO NOT EDIT.\n\npackage x\n\n// c\nfunc F() {}\n", 0},
		"nolint":      {"package x\n\nfunc F() {} //nolint:all\n", 1},
		"license":     {"// Copyright\npackage x\n", 1},
		"too long":    {"package x\n" + strings.Repeat("\n", 301), 1},
		"string only": {"package x\n\nvar S = \"// not a comment\"\n", 0},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			got, err := CheckFile(writeFile(t, tc.src))
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Fatalf("got %v, want %d violations", got, tc.want)
			}
		})
	}
}

func TestCheckFileSyntaxError(t *testing.T) {
	if _, err := CheckFile(writeFile(t, "package")); err == nil {
		t.Fatal("expected error")
	}
}

func TestScanWalksDirectories(t *testing.T) {
	dir := t.TempDir()
	sub := filepath.Join(dir, "sub")
	if err := os.MkdirAll(sub, 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(sub, "a.go"), []byte("package a\n// c\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := Scan([]string{dir + "/..."})
	if err != nil || len(got) != 1 {
		t.Fatalf("got %v, %v", got, err)
	}
}
